"""The MaRI-versus-RI supplementary tables and in-text macros, rendered from a small study.

Every frame below is a hand-built stand-in for ``output/studies/mari-vs-ri/``; the expected
LaTeX is written out literally. ``paper/`` is untracked, so nothing here writes into it.
"""

import sys
from pathlib import Path

import pandas as pd
import pytest

ROOT = Path(__file__).resolve().parents[1]
REPRO = ROOT / "scripts" / "repro"
if str(REPRO) not in sys.path:
    sys.path.insert(0, str(REPRO))

import _mari_vs_ri as mvr  # noqa: E402

CAMELYON, TCGA, TOLKACH = "pathorob-camelyon", "pathorob-tcga-4x4", "pathorob-tolkach-esca"
CONTROL = "DINOv2-B"


def _per_encoder() -> pd.DataFrame:
    """Three ranked encoders and the control per benchmark; the control is always extreme."""
    rows = []
    spec = {
        CAMELYON: (11, [0.40, 0.50, 0.60], [1.10, 1.20, 1.30], [0.010, -0.050, 0.020]),
        TCGA: (81, [0.99, 1.00, 1.00], [1.29, 1.50, 1.68], [0.020, 0.038, -0.010]),
        TOLKACH: (71, [0.90, 0.95, 0.97], [1.31, 1.40, 1.63], [0.030, 0.010, 0.070]),
    }
    within = {CAMELYON: 0.0012, TCGA: -0.0006, TOLKACH: 0.0009}
    for benchmark, (k, support, ratio, delta) in spec.items():
        for i in range(3):
            rows.append(
                dict(
                    benchmark=benchmark,
                    model=f"M{i}",
                    is_control=False,
                    k=k,
                    support=support[i],
                    weight_ratio=ratio[i],
                    delta=delta[i],
                    delta_within=within[benchmark] if i == 1 else 0.0001,
                )
            )
        rows.append(
            dict(
                benchmark=benchmark,
                model=CONTROL,
                is_control=True,
                k=k,
                support=0.01,
                weight_ratio=9.0,
                delta=0.5,
                delta_within=0.4,
            )
        )
    return pd.DataFrame(rows)


def _tau_summary() -> pd.DataFrame:
    rows = []
    for b, benchmark in enumerate((CAMELYON, TCGA, TOLKACH)):
        for f in (0.125, 0.25, 0.5, 1.0, 2.0, 4.0):
            rows.append(
                dict(
                    benchmark=benchmark,
                    f=f,
                    n=3,
                    max_abs_delta=0.0376 / f,
                    rho_ri=0.9 + 0.01 * b,
                    rho_nipd_id=0.8 + 0.01 * b + (0.05 if f == 1.0 else 0.0),
                    rho_nipd_ood=0.7,
                )
            )
    return pd.DataFrame(rows)


def _loo() -> pd.DataFrame:
    """Tolkach: three of five removals move k from 71 to 61. The others never move."""
    rows = []
    for benchmark, run_k in ((CAMELYON, 11), (TCGA, 81), (TOLKACH, 71)):
        for i, model in enumerate(["M0", "M1", "M2", "M3", CONTROL]):
            moves = benchmark == TOLKACH and i >= 2
            rows.append(
                dict(
                    benchmark=benchmark,
                    removed=model,
                    is_control=model == CONTROL,
                    k_star=run_k,
                    run_k=run_k,
                    loo_k=61 if moves else run_k,
                    moves_k=moves,
                    max_abs_delta_ri=0.0123 if moves else float("nan"),
                    max_abs_delta_mari=0.0151 if moves else float("nan"),
                    swapped_pairs=4 if moves else float("nan"),
                    rho_ri=0.99 if moves else float("nan"),
                )
            )
    return pd.DataFrame(rows)


def _study() -> "mvr.Study":
    return mvr.Study(per_encoder=_per_encoder(), tau_summary=_tau_summary(), loo=_loo())


def test_summary_table_ranges_over_ranked_encoders_per_benchmark() -> None:
    tex = mvr.render_summary_table(_study())

    assert r"Camelyon & $3$ & $11$ & $[0.40, 0.60]$ & $[1.10, 1.30]$ & $0.050$ & $0.0012$ \\" in tex
    assert (
        r"TCGA ($4\times4$) & $3$ & $81$ & $[0.99, 1.00]$ & $[1.29, 1.68]$ & $0.038$ & $0.0006$ \\"
    ) in tex
    assert r"\label{tab:mari-vs-ri}" in tex
    assert tex.startswith("% AUTO-GENERATED by scripts/repro/generate_mari_vs_ri_tables.py")


def test_tau_sweep_table_has_one_row_per_temperature_factor() -> None:
    tex = mvr.render_tau_sweep_table(_study())

    # f = 1/4: max |Delta| = 0.0376 * 4; rho(MaRI, RI) and rho(MaRI, nIPD_ID) per benchmark.
    # rho(MaRI, RI) sits near 1 throughout, so it keeps a third decimal.
    assert (
        r"$\tau/4$ & $0.150$ & $0.900$ & $0.80$ & $0.150$ & $0.910$ & $0.81$ "
        r"& $0.150$ & $0.920$ & $0.82$ \\"
    ) in tex
    assert r"$\tau$ & $0.038$ & $0.900$ & $0.85$ &" in tex
    assert r"$4\tau$ & $0.009$ &" in tex
    assert r"\label{tab:mari-tau-sweep}" in tex


def test_macros_cite_the_weight_ratio_range_and_the_shared_k_panel_dependence() -> None:
    lines = mvr.macros(_study())

    assert r"\newcommand{\MariWeightRatioRange}{$[1.10, 1.68]$}" in lines
    assert r"\newcommand{\MariDeltaWithinMax}{$0.0012$}" in lines
    assert r"\newcommand{\TolkachSharedKPanel}{5}" in lines
    assert r"\newcommand{\TolkachSharedKMoves}{3}" in lines
    assert r"\newcommand{\TolkachSharedKAlt}{61}" in lines
    assert r"\newcommand{\TolkachSharedKMaxDeltaRi}{$0.012$}" in lines
    assert r"\newcommand{\TolkachSharedKSwappedPairs}{4}" in lines
    assert r"\newcommand{\CamelyonSharedKMoves}{0}" in lines


def test_macros_leave_the_alternative_k_undefined_where_no_removal_moves_it() -> None:
    """Prose citing a moved k on such a benchmark must fail to compile, not print a dash."""
    text = "\n".join(mvr.macros(_study()))

    assert r"\CamelyonSharedKAlt" not in text
    assert r"\TcgaFourByFourSharedKMaxDeltaRi" not in text


def test_a_missing_study_output_fails_loudly(tmp_path: Path) -> None:
    with pytest.raises(FileNotFoundError, match="scripts/studies/mari_vs_ri.py"):
        mvr.load(tmp_path)


def test_paper_values_fail_rather_than_skip_without_the_study(tmp_path: Path) -> None:
    """The macros are cited inline, so a missing study must stop generated_values.tex."""
    import generate_paper_values as paper_values

    with pytest.raises(FileNotFoundError, match="mari-vs-ri"):
        paper_values.build(paper_values.BENCHMARKS, tmp_path, "auto")


@pytest.mark.parametrize("name", ["mari_vs_ri.tex", "mari_tau_sweep.tex"])
def test_local_paper_tables_are_fresh(name: str) -> None:
    """Where a local paper tree and the study exist, the tables match a rebuild exactly."""
    import generate_mari_vs_ri_tables as generator

    on_disk = ROOT / generator.OUT_DIR / name
    if not on_disk.exists() or not (ROOT / mvr.STUDY_DIR).exists():
        pytest.skip("no local paper tree or study output")
    assert (
        on_disk.read_text() == generator.build(ROOT)[name]
    ), "stale; run python scripts/repro/build_paper.py"


def test_generator_renders_both_tables_from_the_study_directory(tmp_path: Path) -> None:
    import generate_mari_vs_ri_tables as generator

    study_dir = tmp_path / mvr.STUDY_DIR
    study_dir.mkdir(parents=True)
    _per_encoder().to_csv(study_dir / "per_encoder.csv", index=False)
    _tau_summary().to_csv(study_dir / "tau_sweep_summary.csv", index=False)
    _loo().to_csv(study_dir / "shared_k_loo.csv", index=False)

    tables = generator.build(tmp_path)

    assert tables == {
        "mari_vs_ri.tex": mvr.render_summary_table(_study()),
        "mari_tau_sweep.tex": mvr.render_tau_sweep_table(_study()),
    }
