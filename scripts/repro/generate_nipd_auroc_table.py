"""Build ``tab:nipd-auroc``: the downstream association under AUROC beside balanced accuracy.

Rows are metric (CRoMa, RI, MaRI) x score (AUROC, balanced accuracy), with the agreement
between the two nIPDs at the bottom; columns are cohort x regime. CRoMa's block also carries
nIPD from each probe's sensitivity and specificity, on the binary cohorts only. Every number,
including those in the caption, comes from :func:`_nipd_auroc.load`, which fails on a
missing or stale AUROC cell, and :func:`_probe_reductions.load`, which fails on a missing or
stale probe-reductions study.
"""

import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from _nipd_auroc import (  # noqa: E402
    SLIDE_COHORT,
    SLIDE_LABEL,
    NipdAuroc,
    interval,
    load,
    significance,
)
from _paper_tables import CaptionClaimError, num_math  # noqa: E402
from loaders import DATASETS, JOIN_KEYS  # noqa: E402  (_nipd_auroc puts the APD study on the path)
from paper_manifest import by_benchmark  # noqa: E402

OUT = Path("paper/sections/supp/nipd_auroc.tex")
_HEADER = "% AUTO-GENERATED by scripts/repro/generate_nipd_auroc_table.py -- do not edit by hand."

_METRIC_ROWS = [("croma", r"\textbf{\code{CRoMa}}"), ("ri", r"\code{RI}"), ("mari", r"\code{MaRI}")]
_SCORE_ROWS = [("nipd_auroc", "AUROC"), ("nipd_balacc", "Bal.\\ acc.")]
#: nIPD from the probes' per-class recalls, correlated with CRoMa only; binary cohorts only.
_SENS_SPEC_ROWS = [("nipd_sens", "Sensitivity"), ("nipd_spec", "Specificity")]
_SENS_SPEC_WORDS = {"nipd_sens": "sensitivity", "nipd_spec": "specificity"}
_REGIMES = [("id", "ID"), ("ood", "OOD")]
_REGIME_WORDS = {"id": "in domain", "ood": "out of domain"}
DASH = "---"


def _label(dataset: str) -> str:
    if dataset == SLIDE_COHORT:
        return SLIDE_LABEL
    return by_benchmark(DATASETS[dataset]["benchmark"]).short_name


def _count(n: int) -> str:
    """``$2{,}000$``: an integer in math mode with a LaTeX thousands separator."""
    return "$" + f"{n:,}".replace(",", "{,}") + "$"


def _and(items: list[str]) -> str:
    """``a``, ``a and b``, ``a, b and c``."""
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + f" and {items[-1]}"


def _stack(*lines: str) -> str:
    """Lines stacked in one centred cell; plain ``tabular``, so no extra package."""
    return r"\begin{tabular}[c]{@{}c@{}}" + r"\\".join(lines) + r"\end{tabular}"


def _cell(study: NipdAuroc, dataset: str, regime: str, x: str, y: str) -> str:
    row = study.cell(dataset, regime, x, y)
    rho = num_math(float(row["rho"]))
    if dataset == SLIDE_COHORT:
        return _stack(rho, rf"{{\scriptsize{significance('p', float(row['p_value']))}}}")
    lines = [rho, rf"{{\scriptsize{interval(float(row['ci_lo']), float(row['ci_hi']))}}}"]
    if row["in_family"]:
        lines.append(rf"{{\scriptsize{significance('q', float(row['q_value']))}}}")
    return _stack(*lines)


def _datasets(study: NipdAuroc) -> list[str]:
    present = set(study.corr["dataset"])
    return [d for d in JOIN_KEYS if d in present]


def _row(study: NipdAuroc, lead: str, x: str, y: str) -> str:
    cells = [
        _cell(study, dataset, regime, x, y)
        for dataset in _datasets(study)
        for regime, _ in _REGIMES
    ]
    return " & ".join([lead, *cells]) + r" \\"


def _sens_spec_cell(sens_spec: pd.DataFrame, dataset: str, regime: str, target: str) -> str:
    rows = sens_spec[
        (sens_spec["cohort"] == dataset)
        & (sens_spec["regime"] == regime)
        & (sens_spec["target"] == target)
    ]
    if rows.empty:
        if dataset in set(sens_spec["cohort"]):
            raise KeyError(f"no {target} correlation for ({dataset}, {regime})")
        return DASH
    if len(rows) != 1:
        raise KeyError(f"more than one {target} correlation for ({dataset}, {regime})")
    row = rows.iloc[0]
    rho = num_math(float(row["rho"]))
    if dataset == SLIDE_COHORT:
        return _stack(rho, rf"{{\scriptsize{significance('p', float(row['p_value']))}}}")
    lines = [rho, rf"{{\scriptsize{interval(float(row['ci_lo']), float(row['ci_hi']))}}}"]
    if row["in_family"]:
        lines.append(rf"{{\scriptsize{significance('q', float(row['q_value']))}}}")
    return _stack(*lines)


def _sens_spec_row(study: NipdAuroc, sens_spec: pd.DataFrame, target: str, label: str) -> str:
    cells = [
        _sens_spec_cell(sens_spec, dataset, regime, target)
        for dataset in _datasets(study)
        for regime, _ in _REGIMES
    ]
    return " & ".join(["", label, *cells]) + r" \\"


def _check_sens_spec(study: NipdAuroc, sens_spec: pd.DataFrame) -> None:
    """The caption quotes the AUROC study's panel and resampling for every row; hold the
    sensitivity and specificity correlations to them."""
    if set(sens_spec["n_boot"]) != {study.n_boot}:
        raise CaptionClaimError(f"sensitivity n_boot {set(sens_spec['n_boot'])} != {study.n_boot}")
    if set(sens_spec["level"]) != {study.level}:
        raise CaptionClaimError(f"sensitivity CI level {set(sens_spec['level'])} != {study.level}")
    monte_carlo = sens_spec[sens_spec["permutation"] == "monte-carlo"]
    if set(monte_carlo["n_permutations"]) - {study.n_permutations("monte-carlo")}:
        raise CaptionClaimError("the sensitivity rows ran other permutations than the AUROC rows")
    complete = sens_spec[sens_spec["undefined"].fillna("") == ""]
    for dataset, n in zip(complete["cohort"], complete["n"]):
        if int(n) != study.n(dataset):
            raise CaptionClaimError(f"{dataset}: a sensitivity row spans {n} encoders, not the table's")


def _disease_classes(sens_spec: pd.DataFrame) -> str:
    cohorts = list(dict.fromkeys(sens_spec["cohort"]))
    return _and(
        [f"{DATASETS[c]['biological_classes'][1]} on {_label(c)}" for c in cohorts]
    )


def _undefined_sentences(sens_spec: pd.DataFrame) -> str:
    sentences = []
    for row in sens_spec[sens_spec["undefined"].fillna("") != ""].itertuples():
        names = [name.replace("_", r"\_") for name in row.undefined.split(";")]
        has = "has" if len(names) == 1 else "have"
        their = "its" if len(names) == 1 else "their"
        exact = (
            rf", with its exact $p$ over all {_count(int(row.n_permutations))} orderings"
            if row.permutation == "exact"
            else ""
        )
        sentences.append(
            rf" On {_label(row.cohort)} {_REGIME_WORDS[row.regime]}, {_and(names)} {has} a "
            rf"mean {_SENS_SPEC_WORDS[row.target]} at $V{{=}}0$ no better than chance, so "
            rf"{their} \code{{nIPD}} is undefined and that $\rho$ is over the remaining "
            rf"{_count(int(row.n))} encoders{exact}."
        )
    return "".join(sentences)


def _sens_spec_sentence(sens_spec: pd.DataFrame) -> str:
    family = int(sens_spec["in_family"].astype(bool).sum())
    in_family = [_label(c) for c in dict.fromkeys(sens_spec.loc[sens_spec["in_family"], "cohort"])]
    return (
        r" The sensitivity and specificity rows give $\rho$ between \code{CRoMa} and "
        r"\code{nIPD} computed from each probe's sensitivity and specificity, with the "
        rf"disease class as positive ({_disease_classes(sens_spec)}) and chance $0.5$, on the "
        rf"binary cohorts only ({DASH} on the multiclass ones), from the same resamples and "
        rf"permutations. The {_and(in_family)} cells form their own Benjamini--Hochberg family "
        rf"of {_count(family)}, outside the correction above." + _undefined_sentences(sens_spec)
    )


def _caption(study: NipdAuroc, sens_spec: pd.DataFrame) -> str:
    tiles = study.tile_datasets
    ks = [study.operating_k(d) for d in tiles]
    if any(k is None for k in ks):
        raise ValueError(f"a tile cohort has no single operating k: {dict(zip(tiles, ks))}")
    if study.operating_k(SLIDE_COHORT) is not None:
        raise ValueError("PCaBiop's slide encoders are expected to sit at their own k*")
    k_text = _and([rf"$k{{=}}{ks[0]}$", *[f"${k}$" for k in ks[1:]]])
    on = _and([_label(d) for d in tiles])
    level = round(study.level * 100)
    return (
        r"\caption{\textbf{Downstream association under a threshold-free score.} Spearman "
        r"$\rho$ between each representation metric and \code{nIPD} computed from two scores "
        r"of the same linear probes: AUROC (on multiclass cohorts, macro one-vs-rest on the "
        r"probes' raw class margins; chance $0.5$) and balanced accuracy (chance $1/K$ for $K$ "
        r"classes). AUROC needs no decision threshold, so a probe whose decision boundary "
        r"drifts under shortcut training while it still ranks samples correctly loses balanced "
        r"accuracy but not AUROC. Positive values indicate that more robust representations "
        r"undergo less degradation; ID and OOD are the in-domain and out-of-domain arms of "
        r"Table~\ref{tab:apd-correlation}. Each tile cell gives $\rho$ over the "
        rf"{_count(study.n_ranked)} ranked encoders (the natural-image control is excluded), "
        rf"its ${level}\%$ percentile interval over {_count(study.n_boot)} encoder resamples, "
        rf"and the Benjamini--Hochberg $q$ over the {_count(study.family_size)} associations on "
        r"the tile cohorts, from two-sided permutation $p$ values "
        rf"({_count(study.n_permutations('monte-carlo'))} permutations). {SLIDE_LABEL}'s "
        rf"{_count(study.n(SLIDE_COHORT))} whole-slide encoders are too few for inference, so "
        r"its column is descriptive and outside the correction: $\rho$ with its exact "
        rf"two-sided permutation $p$ over all {_count(study.n_permutations('exact'))} "
        r"orderings. The bottom row gives the agreement $\rho$ between the two \code{nIPD}s, "
        r"also outside the correction." + _sens_spec_sentence(sens_spec) + " "
        rf"\code{{RI}} and \code{{MaRI}} are taken at each run's operating point: {k_text} on "
        rf"{on}, and each slide encoder's own $k^\star$ on {SLIDE_LABEL}.}}"
    )


def build(study: NipdAuroc, sens_spec: pd.DataFrame) -> str:
    """The table from the AUROC study and the probe reductions' sensitivity and specificity
    correlations (``_probe_reductions.ProbeReductions.sens_spec_correlations``)."""
    _check_sens_spec(study, sens_spec)
    datasets = _datasets(study)
    n_cols = 2 + 2 * len(datasets)
    header = " & ".join(["", "", *[rf"\multicolumn{{2}}{{c}}{{{_label(d)}}}" for d in datasets]])
    rules = " ".join(rf"\cline{{{3 + 2 * i}-{4 + 2 * i}}}" for i in range(len(datasets)))
    regimes = " & ".join(
        ["Metric", r"\code{nIPD} from", *[label for _ in datasets for _, label in _REGIMES]]
    )
    body = []
    for metric, metric_label in _METRIC_ROWS:
        for i, (score, score_label) in enumerate(_SCORE_ROWS):
            lead = f"{metric_label if i == 0 else ''} & {score_label}"
            body.append(_row(study, lead, metric, score))
        if metric == "croma":
            body.extend(_sens_spec_row(study, sens_spec, t, label) for t, label in _SENS_SPEC_ROWS)
        body.append(r"\hline")
    agreement = r"\multicolumn{2}{l}{Agreement: AUROC vs bal.\ acc.}"
    return (
        "\n".join(
            [
                _HEADER,
                r"\begin{table}[!htbp]",
                r"\centering",
                r"\footnotesize",
                r"\setlength{\tabcolsep}{3pt}",
                rf"\begin{{tabular}}{{ll{'c' * (n_cols - 2)}}}",
                r"\hline",
                header + r" \\",
                rules,
                regimes + r" \\",
                r"\hline",
                *body,
                _row(study, agreement, "nipd_auroc", "nipd_balacc"),
                r"\hline",
                r"\end{tabular}",
                _caption(study, sens_spec),
                r"\label{tab:nipd-auroc}",
                r"\end{table}",
            ]
        )
        + "\n"
    )


def main() -> None:
    import _probe_reductions

    OUT.write_text(build(load(), _probe_reductions.load().sens_spec_correlations))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
