r"""Render ``tab:low-data`` (``supp/low_data.tex``): shortcut susceptibility at fewer tiles.

One block per cohort whose probe sweep was repeated with fewer tiles per training slide, one
row per tile level (the full sweep first): the median and range across the ranked encoders
of the balanced (V = 0) probe's balanced accuracy, in and out of domain, and rho(median
CRoMa, nIPD) in and out of domain with its interval. Which interval -- encoder bootstrap or
two-level -- follows ``generate_apd_floats.CI_DESIGN``, the switch ``tab:apd-correlation``
renders by. Every number comes from :func:`_probe_reductions.load`, which fails on a missing
or stale study.

:func:`macros` emits the in-domain rho at each tile level per cohort for
``generate_paper_values.py``.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import _probe_reductions as basis  # noqa: E402
from _paper_tables import CaptionClaimError, num_math, scriptsize_ci  # noqa: E402
from generate_apd_floats import CI_DESIGN, DESIGNS  # noqa: E402
from loaders import DATASETS  # noqa: E402
from paper_manifest import by_benchmark  # noqa: E402

REPO = basis.REPO
OUT = REPO / "paper/sections/supp/low_data.tex"
LABEL = "tab:low-data"
_HEADER = "% AUTO-GENERATED by scripts/repro/generate_low_data_table.py -- do not edit by hand."
_REGIMES = ("id", "ood")
_COLUMNS = 5


def _label(cohort: str) -> str:
    return by_benchmark(DATASETS[cohort]["benchmark"]).short_name


def _interval_columns(design: str) -> tuple[str, str]:
    if design not in DESIGNS:
        raise ValueError(f"design must be one of {DESIGNS}, not {design!r}")
    return ("two_level_lo", "two_level_hi") if design == "two-level" else ("ci_lo", "ci_hi")


def _estimate(value: float, lo: float, hi: float) -> str:
    return num_math(value) + r"\," + scriptsize_ci(lo, hi)


def _correlation(reductions: basis.ProbeReductions, cohort: str, tiles: int, regime: str):
    corr = reductions.low_data_correlations
    rows = corr[(corr["cohort"] == cohort) & (corr["tiles"] == tiles) & (corr["regime"] == regime)]
    if len(rows) != 1:
        raise KeyError(f"no single low-data correlation for ({cohort}, {tiles}, {regime})")
    return rows.iloc[0]


def _row(reductions: basis.ProbeReductions, cohort: str, tiles: int, design: str) -> str:
    low = reductions.low_data
    ranked = low[(low["cohort"] == cohort) & (low["tiles"] == tiles) & ~low["control"]]
    lo_col, hi_col = _interval_columns(design)
    cells = [f"{tiles} (full)" if tiles == reductions.tile_levels(cohort)[0] else str(tiles)]
    for regime in _REGIMES:
        bacc = ranked[f"bacc_v0_{regime}"]
        cells.append(_estimate(float(bacc.median()), float(bacc.min()), float(bacc.max())))
    for regime in _REGIMES:
        row = _correlation(reductions, cohort, tiles, regime)
        cells.append(_estimate(float(row["rho"]), float(row[lo_col]), float(row[hi_col])))
    return " & ".join(cells) + r" \\"


def _single(reductions: basis.ProbeReductions, column: str):
    values = set(reductions.low_data_correlations[column])
    if len(values) != 1:
        raise CaptionClaimError(f"the low-data correlations disagree on {column}: {values}")
    return values.pop()


def _count(n: int) -> str:
    return "$" + f"{n:,}".replace(",", "{,}") + "$"


def _family(reductions: basis.ProbeReductions) -> str:
    """The q values' family: every low-data association, one Benjamini--Hochberg correction."""
    from _nipd_auroc import significance

    corr = reductions.low_data_correlations
    if not corr["in_family"].astype(bool).all():
        raise CaptionClaimError("a low-data association is outside the table's family")
    n_permutations = _count(int(_single(reductions, "n_permutations")))
    p_values = (
        rf"Exact two-sided permutation $p$ values (over all {n_permutations} orderings)"
        if _single(reductions, "permutation") == "exact"
        else rf"Two-sided permutation $p$ values ({n_permutations} permutations)"
    )
    return (
        rf" {p_values} are Benjamini--Hochberg adjusted over the table's "
        rf"{_count(len(corr))} associations; the largest is "
        rf"{significance('q', float(corr['q_value'].max()))}."
    )


def _caption(reductions: basis.ProbeReductions, design: str) -> str:
    level = round(float(_single(reductions, "level")) * 100)
    n_boot = int(_single(reductions, "n_boot"))
    interval = (
        rf"${level}\%$ encoder-bootstrap interval"
        if design == "encoder"
        else (
            rf"${level}\%$ two-level bootstrap interval, which resamples the encoders and, "
            r"within each drawn encoder, its probe runs (recomputing \code{nIPD}), with every "
            r"encoder's median \code{CRoMa} taken from one stratified slide draw shared across "
            r"encoders"
        )
    )
    return (
        r"\caption{\textbf{Downstream shortcut susceptibility with fewer training tiles.} The "
        r"confounder-biased probe sweep of Table~\ref{tab:split-schedule}, repeated with fewer "
        r"tiles per training slide. Each training slide contributes the stated number of "
        r"tiles, drawn once per replicate and kept at every split, and each cell's validation "
        r"slice shrinks by the same factor (Table~\ref{tab:split-schedule}c); the slides, the "
        r"splits and the held-out test sets are those of the full sweep, the first row of each "
        r"block (as in Table~\ref{tab:apd-correlation}). Balanced accuracy is that of the "
        r"balanced probe (Cramér's $V{=}0$): the median, and in brackets the range, over the "
        rf"{_count(reductions.n_ranked)} ranked encoders (the natural-image control is "
        r"excluded). $\rho$ is Spearman's between median \code{CRoMa} and \code{nIPD} over the "
        r"same encoders, in domain (ID) and out of domain (OOD), with its "
        rf"{interval}, from {_count(n_boot)} replicates." + _family(reductions) + "}"
    )


def build(reductions: basis.ProbeReductions, design: str = CI_DESIGN) -> str:
    _interval_columns(design)
    body = []
    for cohort in reductions.low_data_cohorts:
        body.append(rf"\multicolumn{{{_COLUMNS}}}{{l}}{{\emph{{{_label(cohort)}}}}} \\")
        body.extend(_row(reductions, cohort, t, design) for t in reductions.tile_levels(cohort))
        body.append(r"\hline")
    return (
        "\n".join(
            [
                _HEADER,
                r"\begin{table}[!htbp]",
                r"\centering",
                r"\footnotesize",
                r"\setlength{\tabcolsep}{4pt}",
                r"\begin{tabular}{lcccc}",
                r"\hline",
                r" & \multicolumn{2}{c}{Bal.\ acc.\ at $V{=}0$} & "
                r"\multicolumn{2}{c}{$\rho(\code{CRoMa}, \code{nIPD})$} \\",
                r"\cline{2-3} \cline{4-5}",
                r"Tiles/slide & ID & OOD & ID & OOD \\",
                r"\hline",
                *body,
                r"\end{tabular}",
                _caption(reductions, design),
                rf"\label{{{LABEL}}}",
                r"\end{table}",
            ]
        )
        + "\n"
    )


_ONES = ["", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]
_TEENS = ["Ten", "Eleven", "Twelve", "Thirteen", "Fourteen", "Fifteen", "Sixteen",
          "Seventeen", "Eighteen", "Nineteen"]  # fmt: skip
_TENS = ["", "", "Twenty", "Thirty", "Forty", "Fifty", "Sixty", "Seventy", "Eighty", "Ninety"]


def _words(n: int) -> str:
    """``300`` -> ``ThreeHundred``: LaTeX command names take letters only."""
    if not 1 <= n <= 999:
        raise ValueError(f"no macro spelling for {n} tiles")
    hundreds, rest = divmod(n, 100)
    text = f"{_ONES[hundreds]}Hundred" if hundreds else ""
    if 10 <= rest < 20:
        return text + _TEENS[rest - 10]
    return text + _TENS[rest // 10] + _ONES[rest % 10]


def macro_lines(reductions: basis.ProbeReductions, design: str = CI_DESIGN) -> list[str]:
    """``\\LowDataIdCroma<Cohort>Tiles<N>`` (rho, ``Ci`` and ``Q``) per cohort x tile level.

    The interval is the one ``tab:low-data`` renders (``design``), so the text quotes the
    bracket the table shows.
    """
    from _nipd_auroc import interval, significance
    from _paper_tables import bare_num

    lo_col, hi_col = _interval_columns(design)
    lines = [rf"\newcommand{{\LowDataNModels}}{{{reductions.n_ranked}}}"]
    for cohort in reductions.low_data_cohorts:
        prefix = by_benchmark(DATASETS[cohort]["benchmark"]).prefix
        for tiles in reductions.tile_levels(cohort):
            row = _correlation(reductions, cohort, tiles, "id")
            name = f"LowDataIdCroma{prefix}Tiles{_words(tiles)}"
            ci = interval(float(row[lo_col]), float(row[hi_col]))
            lines += [
                rf"\newcommand{{\{name}}}{{{bare_num(float(row['rho']))}}}",
                rf"\newcommand{{\{name}Ci}}{{{ci}}}",
                rf"\newcommand{{\{name}Q}}{{{significance('q', float(row['q_value']))}}}",
            ]
    return lines


def macros(root: Path = REPO, design: str = CI_DESIGN) -> list[str]:
    """The macros, from the study under ``root``; raises when it is missing or stale."""
    return macro_lines(basis.load(root), design)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()
    out = args.out if args.out.is_absolute() else REPO / args.out
    rendered = build(basis.load(REPO))
    if not out.parent.exists():
        print(f"skip   {out} (paper/ absent)", file=sys.stderr)
        return 0
    out.write_text(rendered)
    print(f"wrote  {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
