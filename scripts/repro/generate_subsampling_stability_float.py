"""Build the cohort-subsampling stability floats (tab:subsampling-stability, fig:subsampling-stability).

Reads the complete study at ``output/studies/subsampling-stability/`` through
``_subsampling.load`` -- a missing replicate, or a full-cohort run that did not reproduce
production, fails the build rather than shrinking the table -- and writes

  paper/sections/supp/table_subsampling_stability.tex    tab:subsampling-stability
  paper/sections/supp/figure_subsampling_stability.tex   fig:subsampling-stability

The figure's PDF is drawn separately, by ``figures/subsampling_stability_figure.py``, into the
study's own ``plots/`` directory. Every number comes from the study's records, and every
caption is a function of the design and of how each full-cohort run reproduced production
alone, so a re-run with the same seed rebuilds both files byte for byte, and no caption
sentence depends on how the results came out.

Run: python scripts/repro/generate_subsampling_stability_float.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
for _p in (REPO / "src", HERE):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

import _subsampling as S  # noqa: E402
from _paper_tables import num_math, pct_round, sci_math, scriptsize_ci  # noqa: E402
from paper_manifest import by_benchmark  # noqa: E402

OUT_DIR = Path("paper/sections/supp")
TABLE_NAME = "table_subsampling_stability.tex"
FIGURE_NAME = "figure_subsampling_stability.tex"
GRAPHIC = "figures/subsampling_stability.pdf"
HEADER = "% AUTO-GENERATED by scripts/repro/generate_subsampling_stability_float.py -- do not edit by hand."

METRIC_TEX = {
    "ri": r"\code{RI}, re-selected $k$",
    "ri_fixed_k": r"\code{RI}, fixed $k$",
    "mari": r"\code{MaRI}, re-selected $k$",
    "mari_fixed_k": r"\code{MaRI}, fixed $k$",
    "croma": r"median \code{CRoMa}",
    "croma_ltm_alpha": r"$\mcode{LTM}_{10}$",
}
VERSUS_TEX = {"ri": r"\code{RI}", "mari": r"\code{MaRI}"}


def _cohort(cohort: str) -> str:
    return by_benchmark(cohort).short_name


def _units(data: S.Study) -> str:
    """``Camelyon $4/8/13$ of $17$ slides, ...``: the design table, read from the study."""
    unit = {
        "pathorob-camelyon": "slides",
        "pathorob-tcga-4x4": "slides",
        "pathorob-tolkach-esca": "case blocks",
    }
    parts = []
    for cohort in data.design["cohorts"]:
        per = data.design["units_per_cell"][cohort]
        kept = "/".join(str(per[str(f)]) for f in data.design["fractions"])
        parts.append(f"{_cohort(cohort)} ${kept}$ of ${per['full']}$ {unit[cohort]}")
    return "; ".join(parts)


def _fixed_k(data: S.Study) -> str:
    full = data.meta[data.meta["fraction"] == S.study.FULL]
    by = dict(zip(full["cohort"], full["shared_k"].astype(int)))
    return ", ".join(f"{_cohort(c)} ${by[c]}$" for c in data.design["cohorts"])


def _n_encoders(data: S.Study) -> int:
    (n,) = set(data.scores.groupby("cohort")["model"].nunique())
    return int(n)


def _fractions(data: S.Study) -> str:
    fs = [f"{f}\\%" for f in data.design["fractions"]]
    return ", ".join(fs[:-1]) + f" and {fs[-1]}"


def _k_grid_clause(data: S.Study) -> str:
    ks = S.k_support_summary(data)
    grid_max = int(ks["k_grid_max"].max())
    usable = int(ks["min_usable_neighbours"].min())
    if grid_max >= usable:
        raise ValueError(f"the k grid ({grid_max}) reaches past {usable} usable neighbours")
    return (
        f"The sparse $k$ grid (largest $k={grid_max}$) stays below every subsample's "
        f"usable-neighbour count, so no fraction caps it."
    )


def _join(items: list[str], last: str = " and ") -> str:
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + last + items[-1]


def _reproduction_clause(data: S.Study) -> str:
    """One sentence, from the reproduction records: which cohorts' full-cohort runs reproduce
    production exactly, and which only within their tolerance, with the largest deviation."""
    record = data.reproduction.set_index("cohort")
    cohorts = data.design["cohorts"]
    within = [c for c in cohorts if not record.loc[c, "identical"]]
    if not within:
        return "The full-cohort run reproduces every published score exactly."
    exact = [_cohort(c) for c in cohorts if c not in within]
    clauses = [f"exactly on {_join(exact)}"] if exact else []
    clauses += [
        f"on {_cohort(c)} only within an absolute tolerance of "
        f"{sci_math(record.loc[c, 'tolerance'])} (largest deviation "
        f"{sci_math(record.loc[c, 'max_deviation'])})"
        for c in within
    ]
    # Every published run used two BLAS kernels across encoders; these mixed them within one.
    its = "its published run" if len(within) == 1 else "their published runs"
    return (
        f"The full-cohort run reproduces the published scores {_join(clauses, ', and ')}, "
        f"because {its} mixed two BLAS kernels within an encoder's scores."
    )


def build_table(data: S.Study) -> str:
    ranking = S.ranking_summary(data)
    paired = S.paired_summary(data)
    ks = S.k_support_summary(data)
    fractions = [int(f) for f in data.design["fractions"]]
    n_metrics = len(S.METRICS)

    lines = [
        HEADER,
        r"\begin{table}[!htbp]",
        r"\centering",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{4pt}",
        r"\textbf{a}\par\smallskip",
        r"\begin{tabular}{ll" + "cc" * len(fractions) + "}",
        r"\hline",
        " & & "
        + " & ".join(rf"\multicolumn{{2}}{{c}}{{{f}\%}}" for f in fractions)
        + r" \\",
        r"Cohort & Metric & " + " & ".join([r"$\tau_K$ & $w$"] * len(fractions)) + r" \\",
        r"\hline",
    ]
    for cohort in data.design["cohorts"]:
        for i, metric in enumerate(S.METRICS):
            label = rf"\multirow{{{n_metrics}}}{{*}}{{{_cohort(cohort)}}}" if i == 0 else ""
            cells = []
            for f in fractions:
                row = ranking[
                    (ranking["cohort"] == cohort)
                    & (ranking["fraction"] == f)
                    & (ranking["metric"] == metric)
                ].iloc[0]
                cells.append(
                    num_math(row["tau_k_median"])
                    + r"\,"
                    + scriptsize_ci(row["tau_k_q25"], row["tau_k_q75"])
                )
                cells.append(num_math(row["rank_width_median"], decimals=1))
            lines.append(f"{label} & {METRIC_TEX[metric]} & " + " & ".join(cells) + r" \\")
        lines.append(r"\hline")
    lines += [
        r"\end{tabular}",
        r"\par\medskip",
        r"\textbf{b}\par\smallskip",
        r"\begin{tabular}{llcccc}",
        r"\hline",
        r"Cohort & Fraction & "
        + " & ".join(rf"$\Delta\tau_K$ vs {VERSUS_TEX[v]}" for v in S.PAIRED_AGAINST)
        + r" & Shared $k$ & \code{RI} support \\",
        r"\hline",
    ]
    n_rep = int(data.design["n_replicates"])
    for cohort in data.design["cohorts"]:
        for i, f in enumerate(fractions):
            label = rf"\multirow{{{len(fractions)}}}{{*}}{{{_cohort(cohort)}}}" if i == 0 else ""
            cells = []
            for against in S.PAIRED_AGAINST:
                row = paired[
                    (paired["cohort"] == cohort)
                    & (paired["fraction"] == f)
                    & (paired["versus"] == against)
                ].iloc[0]
                cells.append(
                    num_math(row["tau_k_diff_median"])
                    + r"\,"
                    + scriptsize_ci(row["tau_k_diff_lo"], row["tau_k_diff_hi"])
                    + rf"\,({int(row['n_croma_higher'])}/{n_rep})"
                )
            k = ks[(ks["cohort"] == cohort) & (ks["fraction"] == f)].iloc[0]
            lo, hi = int(k["shared_k_min"]), int(k["shared_k_max"])
            cells.append(f"${lo}$" if lo == hi else f"${lo}$--${hi}$")
            cells.append(
                f"{pct_round(k['support_median'])} ({pct_round(k['full_support_median'])})"
            )
            lines.append(f"{label} & {f}\\% & " + " & ".join(cells) + r" \\")
        lines.append(r"\hline")
    lines += [r"\end{tabular}", "\\caption{" + _table_caption(data) + "}"]
    lines += [r"\label{tab:subsampling-stability}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def _table_caption(data: S.Study) -> str:
    n_rep = int(data.design["n_replicates"])
    return (
        r"\textbf{Score and ranking stability under cohort subsampling.} "
        r"Each tile cohort is subsampled without replacement within every "
        r"class$\times$centre cell, keeping a fixed number of units per cell at "
        f"{_fractions(data)} ({_units(data)}). Each fraction has ${n_rep}$ replicates, "
        r"one draw is shared by every encoder and metric, and every score is recomputed "
        r"on the subsample. "
        r"\textbf{a}, Kendall's $\tau_K$ between each replicate's ranking of the "
        f"${_n_encoders(data)}$ pathology encoders and the same metric's full-cohort "
        r"ranking: median {\scriptsize[IQR]} over replicates. $w$ is the median over "
        r"encoders of the 2.5--97.5 percentile range of an encoder's rank across "
        r"replicates. Re-selected $k$ re-runs the median-$k$ protocol on the subsample; "
        f"fixed $k$ holds the full-cohort shared $k$ ({_fixed_k(data)}). "
        r"\textbf{b}, per replicate, $\tau_K$ of median \code{CRoMa} minus that of "
        r"\code{RI} and of \code{MaRI}, both at re-selected $k$: median "
        r"{\scriptsize[2.5--97.5 percentile range]} and the number of replicates in which "
        r"\code{CRoMa}'s is higher. Shared $k$ is the range of the re-selected shared $k$ "
        r"over replicates. \code{RI} support is the median over encoders and replicates of "
        r"the share of anchors with a defined \code{RI}, with the full-cohort value in "
        f"parentheses. {_k_grid_clause(data)} {_reproduction_clause(data)} "
        r"The natural-image control is computed but "
        r"excluded from every ranking and summary."
    )


def build_figure(data: S.Study) -> str:
    n_rep = int(data.design["n_replicates"])
    caption = (
        r"\textbf{Ranking stability under cohort subsampling.} One column per tile "
        r"cohort. Top: Kendall's $\tau_K$ between each replicate's ranking of the "
        f"${_n_encoders(data)}$ pathology encoders and the same metric's full-cohort "
        r"ranking, against the share of units kept in every class$\times$centre cell "
        f"(median line and interquartile band over ${n_rep}$ replicates; $100\\%$ is the "
        r"full cohort, where $\tau_K=1$). Bottom: the median over encoders of the "
        r"2.5--97.5 percentile range of an encoder's rank across replicates. Solid "
        r"\code{RI} and \code{MaRI} lines re-select $k$ on each subsample, and dashed lines "
        r"hold the full-cohort shared $k$. The natural-image control is excluded. Values are "
        r"in Table~\ref{tab:subsampling-stability}."
    )
    return "\n".join(
        [
            HEADER,
            "% The PDF is drawn by scripts/repro/figures/subsampling_stability_figure.py, into",
            "% output/studies/subsampling-stability/plots/pdf/subsampling_stability.pdf.",
            "% It is NOT staged: copy that file to paper/figures/subsampling_stability.pdf to",
            "% resolve the \\includegraphics below (\\graphicspath reaches paper/figures/, not output/).",
            r"\begin{figure}[!htbp]",
            r"\centering",
            rf"\includegraphics[width=\linewidth]{{{GRAPHIC}}}",
            "\\caption{" + caption + "}",
            r"\label{fig:subsampling-stability}",
            r"\end{figure}",
        ]
    ) + "\n"


def write(data: S.Study, out_dir: Path = OUT_DIR) -> list[Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, build in ((TABLE_NAME, build_table), (FIGURE_NAME, build_figure)):
        path = out_dir / name
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(build(data))
        written.append(path)
    return written


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=Path, default=None, help="the study tree")
    parser.add_argument("--out-dir", type=Path, default=OUT_DIR)
    args = parser.parse_args(argv)
    for path in write(S.load(args.root), args.out_dir):
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
