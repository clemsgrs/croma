"""Build the cross-benchmark rank figure's float and caption (fig:cross-benchmark).

The PDF is drawn by ``scripts/repro/figures/cross_benchmark_figure.py``; both read
``_cross_benchmark.load()``. The caption defines the trajectories and marker encodings without
narrating individual model rankings (ADR-0010).

Run: python scripts/repro/generate_cross_benchmark_float.py
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from _cross_benchmark import (  # noqa: E402
    CROMA_HEADLINE_M,
    load,
)

OUT = Path("paper/sections/supp_cross_benchmark.tex")
GRAPHIC = "figures/cross_benchmark.pdf"

def build() -> str:
    cb = load()
    benchmarks = ", ".join(cb.labels[:-1]) + " and " + cb.labels[-1]
    caption = " ".join([
        r"\caption{\textbf{\code{CRoMa} rankings across PathoROB tile benchmarks.}",
        rf"Trajectories show the rank of {cb.n_models} pathology encoders by pooled "
        rf"$\mcode{{CRoMa}}(m{{=}}{int(CROMA_HEADLINE_M)})$ across {benchmarks} "
        r"(rank $1$, top). End labels report \code{CRoMa} on the first and last benchmarks.",
        r"Markers are filled for $\mcode{CRoMa}\ge0$ and hollow for $\mcode{CRoMa}<0$.",
        rf"Dashed trajectories and $\dagger$ mark the {len(cb.exposed)} TCGA-exposed encoders.",
        r"The natural-image control is excluded.",
    ]) + "}"

    return "\n".join([
        "% AUTO-GENERATED by scripts/repro/generate_cross_benchmark_float.py -- do not edit by hand.",
        "% The PDF is drawn by scripts/repro/figures/cross_benchmark_figure.py from the same loader.",
        r"\begin{figure}[!htbp]",
        r"\centering",
        rf"\includegraphics[width=0.9\linewidth]{{{GRAPHIC}}}",
        caption,
        r"\label{fig:cross-benchmark}",
        r"\end{figure}",
    ]) + "\n"


def main() -> None:
    OUT.write_text(build())
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
