"""Shared basis for the MaRI-versus-RI supplementary tables and in-text macros.

The study (``scripts/studies/mari_vs_ri.py``) writes ``output/studies/mari-vs-ri/``. Two
consumers read it and must agree:

* ``generate_mari_vs_ri_tables.py`` renders ``tab:mari-vs-ri`` and ``tab:mari-tau-sweep``;
* ``generate_paper_values.py`` emits the scalars the text cites inline.

Ranges and maxima are over the ranked encoders (the natural-image control excluded). The
shared-k panel size counts every evaluated encoder, the control included, because the
production median does. A missing study output raises: these tables and macros are cited,
so a warn-and-skip would silently delete them.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
for _path in (REPO / "src", HERE):
    if str(_path) not in sys.path:
        sys.path.insert(0, str(_path))

from _cross_benchmark import PANEL, short_label  # noqa: E402
from _paper_tables import bare_num, num_math  # noqa: E402
from paper_manifest import by_benchmark  # noqa: E402

STUDY_DIR = Path("output/studies/mari-vs-ri")
REMEDY = "run scripts/studies/mari_vs_ri.py"
GENERATOR = "scripts/repro/generate_mari_vs_ri_tables.py"


@dataclass(frozen=True)
class Study:
    """The three study tables the paper artifacts are rendered from."""

    per_encoder: pd.DataFrame
    tau_summary: pd.DataFrame
    loo: pd.DataFrame


def load(root: Path = REPO) -> Study:
    frames = {}
    for name in ("per_encoder", "tau_sweep_summary", "shared_k_loo"):
        path = Path(root) / STUDY_DIR / f"{name}.csv"
        if not path.exists():
            raise FileNotFoundError(f"missing {path}; {REMEDY}")
        frames[name] = pd.read_csv(path, float_precision="round_trip")
    return Study(frames["per_encoder"], frames["tau_sweep_summary"], frames["shared_k_loo"])


def _ranked(study: Study, benchmark: str) -> pd.DataFrame:
    rows = study.per_encoder[study.per_encoder["benchmark"] == benchmark]
    if rows.empty:
        raise ValueError(f"the MaRI-versus-RI study has no rows for {benchmark}; {REMEDY}")
    return rows[~rows["is_control"].astype(bool)]


def _range(values: pd.Series, decimals: int) -> str:
    lo, hi = float(values.min()), float(values.max())
    return rf"$[{bare_num(lo, decimals)}, {bare_num(hi, decimals)}]$"


def _k(values: pd.Series) -> str:
    ks = sorted({int(k) for k in values})
    return f"${ks[0]}$" if len(ks) == 1 else rf"$[{ks[0]}, {ks[-1]}]$"


def _wrap(columns: str, header: list[str], body: list[str], caption: str, label: str) -> str:
    return (
        "\n".join(
            [
                f"% AUTO-GENERATED by {GENERATOR} -- do not edit by hand.",
                r"\begin{table}[!htbp]",
                "\t" + r"\centering",
                "\t" + r"\small",
                "\t" + rf"\begin{{tabular}}{{{columns}}}",
                "\t\t" + r"\hline",
                *["\t\t" + line for line in header],
                "\t\t" + r"\hline",
                *["\t\t" + line for line in body],
                "\t\t" + r"\hline",
                "\t" + r"\end{tabular}",
                "\t" + caption,
                "\t" + rf"\label{{{label}}}",
                r"\end{table}",
            ]
        )
        + "\n"
    )


def render_summary_table(study: Study) -> str:
    """``tab:mari-vs-ri``: one row per tile benchmark, over its ranked encoders."""
    body = []
    for benchmark in PANEL:
        ranked = _ranked(study, benchmark)
        body.append(
            f"{short_label(benchmark)} & ${len(ranked)}$ & {_k(ranked['k'])} & "
            f"{_range(ranked['support'], 2)} & {_range(ranked['weight_ratio'], 2)} & "
            f"{num_math(float(ranked['delta'].abs().max()), 3)} & "
            rf"{num_math(float(ranked['delta_within'].abs().max()), 4)} \\"
        )
    header = [
        r"Benchmark & $n$ & $k$ & Support & Weight ratio & $\max|\Delta|$ & "
        r"$\max|\Delta_{\mathrm{within}}|$ \\"
    ]
    caption = (
        r"\caption{\textbf{Decomposition of the difference between \code{MaRI} and \code{RI} "
        r"on the tile benchmarks.} Each row summarises the $n$ ranked encoders of one "
        r"benchmark, excluding the natural-image control, at the benchmark's shared operating "
        r"$k$ and each encoder's automatic $\tau$. Support is the fraction of anchors with at "
        r"least one typed (\textbf{SO} or \textbf{OS}) neighbour among their $k$ nearest. The "
        r"weight ratio is, per encoder, the median over anchors of "
        r"$\exp\!\left((d_{(k)}-d_{(1)})/\tau\right)$, the weight an anchor's nearest valid "
        r"neighbour receives relative to its $k$-th; ranges are taken over encoders. "
        r"$\Delta=\mcode{MaRI}-\mcode{RI}$, and $\Delta_{\mathrm{within}}$ is the part of "
        r"$\Delta$ that re-weights each anchor's own typed neighbours at fixed count; the "
        r"remainder of $\Delta$ re-weights anchors against one another. Both maxima are taken "
        r"over encoders.}"
    )
    return _wrap("lcccccc", header, body, caption, "tab:mari-vs-ri")


def _factor(f: float) -> str:
    if f == 1.0:
        return r"$\tau$"
    if f < 1.0:
        return rf"$\tau/{round(1.0 / f)}$"
    return rf"${round(f)}\tau$"


def render_tau_sweep_table(study: Study) -> str:
    """``tab:mari-tau-sweep``: one row per temperature factor, three columns per benchmark."""
    summary = study.tau_summary.set_index(["benchmark", "f"])
    factors = sorted(study.tau_summary["f"].unique())
    body = []
    for f in factors:
        cells = [_factor(float(f))]
        for benchmark in PANEL:
            row = summary.loc[(benchmark, f)]
            # rho(MaRI, RI) sits near 1 at every factor; two decimals would flatten it to 1.00.
            cells += [
                num_math(float(row["max_abs_delta"]), 3),
                num_math(float(row["rho_ri"]), 3),
                num_math(float(row["rho_nipd_id"]), 2),
            ]
        body.append(" & ".join(cells) + r" \\")
    groups = " & ".join(rf"\multicolumn{{3}}{{c}}{{{short_label(b)}}}" for b in PANEL)
    per_benchmark = r"$\max|\Delta|$ & $\rho_{\code{RI}}$ & $\rho_{\code{nIPD}}$"
    header = [
        rf" & {groups} \\",
        "Temperature & " + " & ".join([per_benchmark] * len(PANEL)) + r" \\",
    ]
    caption = (
        r"\caption{\textbf{Sensitivity of \code{MaRI} to the temperature $\tau$.} Each "
        r"encoder's \code{MaRI} is rescored on the same neighbours at its shared operating $k$, "
        r"with the temperature set to a multiple of its automatic $\tau$ (the row label); "
        r"$\tau$ itself is the published setting. For each tile benchmark, over the ranked "
        r"encoders (excluding the natural-image control), $\max|\Delta|$ is the largest "
        r"$|\mcode{MaRI}-\mcode{RI}|$, $\rho_{\code{RI}}$ the Spearman correlation between the "
        r"rescored \code{MaRI} and \code{RI}, and $\rho_{\code{nIPD}}$ the Spearman correlation "
        r"between the rescored \code{MaRI} and in-domain \code{nIPD}.}"
    )
    columns = "l" + "ccc" * len(PANEL)
    return _wrap(columns, header, body, caption, "tab:mari-tau-sweep")


def _macro(name: str, value: str) -> str:
    return rf"\newcommand{{\{name}}}{{{value}}}"


def macros(study: Study) -> list[str]:
    """In-text scalars: the weight-ratio range, the within-anchor bound, shared-k floating."""
    ranked = pd.concat([_ranked(study, b) for b in PANEL])
    lines = [
        f"% MaRI versus RI ({STUDY_DIR}): weight ratio and within-anchor Delta, tile benchmarks",
        _macro("MariWeightRatioRange", _range(ranked["weight_ratio"], 2)),
        _macro("MariDeltaWithinMax", num_math(float(ranked["delta_within"].abs().max()), 4)),
    ]
    for benchmark in PANEL:
        prefix = by_benchmark(benchmark).prefix
        loo = study.loo[study.loo["benchmark"] == benchmark]
        if loo.empty:
            raise ValueError(f"the shared-k leave-one-out has no rows for {benchmark}; {REMEDY}")
        moved = loo[loo["moves_k"].astype(bool)]
        lines += [
            f"% {prefix}: shared median k under single-encoder removal",
            _macro(f"{prefix}SharedKPanel", str(len(loo))),
            _macro(f"{prefix}SharedKMoves", str(len(moved))),
        ]
        if moved.empty:
            continue
        alternatives = sorted({int(k) for k in moved["loo_k"]})
        if len(alternatives) != 1:
            raise ValueError(f"{benchmark}: single removals move k to {alternatives}")
        at = moved.iloc[0]
        lines += [
            _macro(f"{prefix}SharedKAlt", str(alternatives[0])),
            _macro(f"{prefix}SharedKMaxDeltaRi", num_math(float(at["max_abs_delta_ri"]), 3)),
            _macro(f"{prefix}SharedKSwappedPairs", str(int(at["swapped_pairs"]))),
        ]
    return lines
