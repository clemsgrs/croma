"""Build the nIPD figures and downstream-correlation supplementary table."""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from _apd import SLIDE_DATASET, Apd, FIGURE_DATASETS, load  # noqa: E402
from _paper_tables import CaptionClaimError  # noqa: E402

FIGURE_OUT = Path("paper/sections/results_figure_apd.tex")
SUPP_FIGURE_OUT = Path("paper/sections/supp/figure_apd.tex")
TABLE_OUT = Path("paper/sections/supp/apd_correlation.tex")
PCABIOP_FIGURE_OUT = Path("paper/sections/supp/figure_apd_pcabiop.tex")

MAIN_FIGURE_DATASETS = ["camelyon"]
SUPP_FIGURE_DATASETS = ["tcga_4x4", "tolkach"]
GRAPHIC_SOURCE_DIR = "output/studies/apd/plots/pdf"
_HEADER = "% AUTO-GENERATED by scripts/repro/generate_apd_floats.py -- do not edit by hand."

#: Which bootstrap interval tab:apd-correlation shows for rho(median CRoMa, nIPD): "encoder"
#: (resample the encoders) or "two-level" (resample encoders, then each one's probe runs and
#: slides). The CSV carries both; every other association has the encoder interval only.
#: generate_paper_values.py quotes the same interval.
CI_DESIGN = "encoder"
DESIGNS = ("encoder", "two-level")

_CROMA = r"\textbf{\code{CRoMa}}"
_LTM = r"$\mcode{LTM}_{10}$"
_F0 = r"$F(0)$"
_GIVEN = r"\,|\,$median"
#: (row label, metric) per block; the partial rows are given median CRoMa.
_NIPD_ID_ROWS = [
    (_CROMA, "croma"),
    (r"\code{RI}", "ri"),
    (r"\code{MaRI}", "mari"),
    (_LTM, "croma_ltm_alpha"),
    (_F0, "croma_f0"),
    (_LTM[:-1] + _GIVEN, "croma_ltm_alpha_given_croma"),
    (_F0[:-1] + _GIVEN, "croma_f0_given_croma"),
]
_NIPD_OOD_ROWS = _NIPD_ID_ROWS[:3]


def _graphic(dataset: str) -> str:
    return f"croma_nipd_{dataset}.pdf"


def _fig_label(dataset: str) -> str:
    return "fig:croma-nipd-" + dataset.replace("_", "")


def _significance(symbol: str, value: float) -> str:
    if value < 0.001:
        return rf"${symbol}{{<}}0.001$"
    return rf"${symbol}{{=}}{value:.{3 if value < 0.01 else 2}f}$"


def _cell(apd: Apd, target: str, metric: str, scope: str, design: str) -> str:
    """rho, its 95% interval, and q (tile benchmarks) or the exact p (PCaBiop)."""
    if scope == SLIDE_DATASET and metric.endswith("_given_croma"):
        return "---"
    row = apd.row(target, metric, scope)
    lo, hi = row["ci_lo"], row["ci_hi"]
    if design == "two-level" and metric == "croma" and target.startswith("nipd_"):
        if scope != SLIDE_DATASET:
            lo, hi = row["two_level_lo"], row["two_level_hi"]
    if bool(row["in_bh_family"]):
        test = _significance("q", float(row["q_bh"]))
    else:
        test = _significance("p", float(row["perm_p"]))
    rho = f"${float(row['spearman']):.2f}$"
    return rf"{rho}\,{{\scriptsize$[{lo:.2f}, {hi:.2f}]$; {test}}}"


def _block(apd: Apd, target: str, label: str, rows: list, design: str) -> list[str]:
    lines = []
    for i, (row_label, metric) in enumerate(rows):
        lead = rf"\multirow{{{len(rows)}}}{{*}}{{{label}}}" if i == 0 else ""
        cells = [_cell(apd, target, metric, s, design) for s in (*FIGURE_DATASETS, SLIDE_DATASET)]
        lines.append(" & ".join([lead, row_label, *cells]) + r" \\")
    return lines


def _reference_row(apd: Apd, target: str, label: str, design: str) -> str:
    cells = [_cell(apd, target, "croma", s, design) for s in (*FIGURE_DATASETS, SLIDE_DATASET)]
    return " & ".join([label, _CROMA, *cells]) + r" \\"


def _table_caption(apd: Apd, design: str) -> str:
    family = apd.corr[apd.corr["in_bh_family"].astype(bool)]
    if set(family["scope"]) != set(FIGURE_DATASETS):
        raise CaptionClaimError(f"the BH family spans {sorted(set(family['scope']))}")
    tile, slide = list(FIGURE_DATASETS), [SLIDE_DATASET]
    n_boot = int(apd.single("n_boot", tile + slide))
    n_perm = int(apd.single("n_permutations", tile))
    if apd.single("permutation", slide) != "exact":
        raise CaptionClaimError("the caption says PCaBiop's p is exact")
    n_exact = int(apd.single("n_permutations", slide))
    n_slide = apd.n(SLIDE_DATASET)
    intervals = (
        r"95\% encoder-bootstrap intervals"
        if design == "encoder"
        else (
            r"95\% intervals: for \code{CRoMa} against \code{nIPD} on the tile benchmarks, a "
            r"two-level bootstrap that resamples the encoders and, within each drawn encoder, "
            r"its probe runs (recomputing \code{nIPD}), with every encoder's median "
            r"\code{CRoMa} taken from one stratified slide draw shared across encoders; "
            r"elsewhere encoder-bootstrap intervals"
        )
    )
    return (
        r"\caption{\textbf{Per-benchmark association between representation robustness and "
        r"downstream shortcut susceptibility.} Spearman $\rho$ relates each representation "
        r"metric to normalized integrated performance degradation (\code{nIPD}), the primary "
        r"downstream reduction. Positive values indicate that more robust representations "
        r"undergo less degradation. The in-domain arm holds acquisition groups fixed and is "
        r"the primary mechanistic endpoint; the out-of-domain arm uses unseen acquisition "
        r"groups and additionally reflects distribution shift. Each tile benchmark contains "
        r"\ApdNModels{} ranked tile encoders. Under \code{nIPD}$_\mathrm{ID}$, "
        r"$\mcode{LTM}_{10}$ and $F(0)$ are correlated plainly and given median \code{CRoMa} "
        r"(partial Spearman, Freedman--Lane permutation $p$); $F(0)$ is lower-is-better, so "
        r"its expected sign is negative. The final two rows repeat the \code{CRoMa} analysis "
        r"using PathoROB's original \code{APD} for continuity. "
        rf"Brackets are {intervals}, from ${n_boot}$ replicates that resample the encoders "
        r"of this table with replacement, so they are over this panel of encoders. $q$ is the "
        r"Benjamini--Hochberg-adjusted two-sided permutation $p$ "
        rf"(${n_perm}$ permutations) over the family of the ${len(family)}$ tile-benchmark "
        rf"associations shown. PCaBiop's ${n_slide}$ whole-slide encoders are reported "
        rf"descriptively, outside that family, with the exact permutation $p$ over all "
        rf"${n_exact}$ orderings; partial correlations are not computed for them.}}"
    )


def build_table(apd: Apd, design: str = CI_DESIGN) -> str:
    if design not in DESIGNS:
        raise ValueError(f"design must be one of {DESIGNS}, not {design!r}")
    apd.assert_control_excluded()
    labels = [*apd.benchmark_labels(), apd.slide_label]
    return "\n".join(
        [
            _HEADER,
            r"\begin{table}[!htbp]",
            r"\centering",
            r"\scriptsize",
            r"\setlength{\tabcolsep}{3pt}",
            r"\begin{tabular}{llccc|c}",
            r"\hline",
            " & Metric & " + " & ".join(labels) + r" \\",
            r"\hline",
            *_block(apd, "nipd_id", r"\code{nIPD}$_\mathrm{ID}$", _NIPD_ID_ROWS, design),
            r"\hline",
            *_block(apd, "nipd_ood", r"\code{nIPD}$_\mathrm{OOD}$", _NIPD_OOD_ROWS, design),
            r"\hline",
            _reference_row(apd, "apd_id", r"\code{APD}$_\mathrm{ID}$", design),
            _reference_row(apd, "apd_ood", r"\code{APD}$_\mathrm{OOD}$", design),
            r"\hline",
            r"\end{tabular}",
            _table_caption(apd, design),
            r"\label{tab:apd-correlation}",
            r"\end{table}",
        ]
    ) + "\n"


def _caption(dataset_label: str, n: int, *, supplementary: bool) -> str:
    title = (
        rf"\textbf{{\code{{CRoMa}} and \code{{nIPD}} on {dataset_label}.}}"
        if supplementary
        else rf"\textbf{{\code{{CRoMa}} against \code{{nIPD}} on {dataset_label}.}}"
    )
    tail = (
        r" Corresponding \code{RI}, \code{MaRI}, and legacy \code{APD} correlations are "
        r"reported in Table~\ref{tab:apd-correlation}."
        if supplementary
        else ""
    )
    return (
        rf"\caption{{{title} Columns show in-domain evaluation (left, acquisition groups "
        r"held fixed) and out-of-domain evaluation (right, unseen acquisition groups). "
        r"\textbf{Top row:} normalized performance change $g(V)$ relative to the "
        r"above-chance performance at $V=0$ as the training-set "
        rf"confounder--biology correlation increases to $V{{=}}1$; curves "
        rf"denote the ${n}$ tile encoders and error bars are 95\% $t$-intervals over "
        r"repeated training runs. \textbf{Bottom row:} pooled \code{CRoMa}$(m{=}5)$ versus "
        r"\code{nIPD}, one point per encoder. Dashed lines mark $g(V)=0$, "
        r"$\mcode{CRoMa}=0$ and "
        rf"$\mcode{{nIPD}}=0$.{tail}}}"
    )


def _figure_blocks(apd: Apd, datasets: list[str], *, supplementary: bool) -> str:
    labels = dict(zip(FIGURE_DATASETS, apd.benchmark_labels()))
    lines = [
        _HEADER,
        f"% PDFs are rendered under {GRAPHIC_SOURCE_DIR}/croma_nipd_<benchmark>.pdf.",
    ]
    for dataset in datasets:
        lines.extend(
            [
                r"\begin{figure}[!htbp]",
                r"\centering",
                rf"\includegraphics[width=0.92\linewidth]{{{_graphic(dataset)}}}",
                _caption(labels[dataset], apd.n_models, supplementary=supplementary),
                rf"\label{{{_fig_label(dataset)}}}",
                r"\end{figure}",
            ]
        )
    return "\n".join(lines) + "\n"


def build_pcabiop_figure() -> str:
    """Render the float for the descriptive five-encoder slide-level composite."""
    return "\n".join(
        [
            _HEADER,
            r"\begin{figure}[!htbp]",
            r"\centering",
            r"\includegraphics[width=0.92\linewidth]{croma_nipd_pcabiop.pdf}",
            (
                r"\caption{\textbf{\code{CRoMa} against \code{nIPD} on PCaBiop.} "
                r"Columns show in-domain evaluation on PANDA acquisition groups represented "
                r"during training (left) and out-of-domain evaluation on the held-out PAR "
                r"cohort (right). \textbf{Top row:} normalized performance change $g(V)$ "
                r"relative to the above-chance performance at $V=0$ as the training-set "
                r"confounder--biology correlation increases to $V=1$; curves denote the "
                r"five whole-slide encoders and error bars are 95\% $t$-intervals over "
                r"repeated training runs. \textbf{Bottom row:} pooled "
                r"\code{CRoMa}$(m{=}5)$ versus \code{nIPD}, one point per encoder. Dashed "
                r"lines mark $g(V)=0$, $\mcode{CRoMa}=0$ and $\mcode{nIPD}=0$. Spearman "
                r"coefficients are descriptive because the panel contains only $n=5$ "
                r"encoders.}"
            ),
            r"\label{fig:croma-nipd-pcabiop}",
            r"\end{figure}",
        ]
    ) + "\n"


def main() -> None:
    assert MAIN_FIGURE_DATASETS + SUPP_FIGURE_DATASETS == FIGURE_DATASETS
    apd = load()
    FIGURE_OUT.write_text(_figure_blocks(apd, MAIN_FIGURE_DATASETS, supplementary=False))
    SUPP_FIGURE_OUT.write_text(
        _figure_blocks(apd, SUPP_FIGURE_DATASETS, supplementary=True)
    )
    PCABIOP_FIGURE_OUT.write_text(build_pcabiop_figure())
    TABLE_OUT.write_text(build_table(apd))
    print(
        f"wrote {FIGURE_OUT}\n"
        f"wrote {SUPP_FIGURE_OUT}\n"
        f"wrote {PCABIOP_FIGURE_OUT}\n"
        f"wrote {TABLE_OUT}"
    )


if __name__ == "__main__":
    main()
